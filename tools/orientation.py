"""Writes addons/bichig/orientation.gd from Unicode's VerticalOrientation.txt.

    python3 -I tools/orientation.py path/to/VerticalOrientation.txt
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "addons" / "bichig" / "orientation.gd"
KINDS = {"U": 1, "Tu": 1, "Tr": 2}


def main() -> None:
    source = Path(sys.argv[1]).read_text(encoding="utf-8")
    version = source.splitlines()[0].lstrip("# ").removesuffix(".txt")
    spans: list[list[int]] = []
    for row in source.splitlines():
        found = re.match(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)", row)
        if not found or found[3] not in KINDS:
            continue
        first, last, kind = int(found[1], 16), int(found[2] or found[1], 16), KINDS[found[3]]
        if spans and spans[-1][1] + 1 == first and spans[-1][2] == kind:
            spans[-1][1] = last
        else:
            spans.append([first, last, kind])
    flat = ", ".join(f"0x{value:X}" if at % 3 < 2 else str(value) for span in spans for at, value in enumerate(span))
    OUT.write_text(
        f"# Generated by tools/orientation.py from {version}. Do not edit.\n"
        "# Triples: first, last, kind. 1 stands upright, 2 stands upright only in its vertical form.\n"
        f"const SPANS: PackedInt32Array = [{flat}]\n"
        "\n\n"
        "static func of(code: int) -> int:\n"
        "\tvar low := 0\n"
        "\tvar high := SPANS.size() / 3 - 1\n"
        "\twhile low <= high:\n"
        "\t\tvar mid := (low + high) / 2\n"
        "\t\tif code < SPANS[mid * 3]:\n"
        "\t\t\thigh = mid - 1\n"
        "\t\telif code > SPANS[mid * 3 + 1]:\n"
        "\t\t\tlow = mid + 1\n"
        "\t\telse:\n"
        "\t\t\treturn SPANS[mid * 3 + 2]\n"
        "\treturn 0\n",
        encoding="utf-8",
    )
    print(f"{len(spans)} spans")


main()
